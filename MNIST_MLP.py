import numpy as np
import mnist
import matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow.keras.callbacks import ModelCheckpoint
from keras.models import Sequential
from keras.layers import Dense
from keras.utils import to_categorical
from sklearn.preprocessing import MinMaxScaler


train_images = mnist.train_images()
train_labels = mnist.train_labels()

test_images = mnist.test_images()
test_labels = mnist.test_labels()

#normalization and flattening (28*28 to 784)
train_images = train_images.reshape((-1,784))
test_images = test_images.reshape((-1,784))

scaler = MinMaxScaler().fit(train_images)
train_images = scaler.transform(train_images)
test_images = scaler.transform(test_images)

# 3 layers, 2 layers with 64 neurons and relu , 1 layer with 10 neurons and softmax
model = Sequential()
model.add(Dense(64, activation='relu', input_dim=784))
model.add(Dense(64, activation='relu'))
model.add(Dense(10, activation='softmax'))

# compile the model
model.compile(
    optimizer='adam',
    loss = 'categorical_crossentropy',
    metrics=['accuracy']
)

#model.summary()

# train the model and save the best model

# add a checkpoint to save the lowest validation loss
filepath = 'tf2_mnist_model.hdf5'

checkpoint = ModelCheckpoint(filepath, monitor='val_accuracy', verbose=1, \
                             save_best_only=True, save_weights_only=False, \
                             mode='auto', save_frequency=1)

history = model.fit(
    train_images,
    to_categorical(train_labels),
    verbose = 1,
    epochs = 50,
    batch_size = 50,
    validation_split=0.2, shuffle = True,
    callbacks=[checkpoint]
)

_, ax = plt.subplots()
plt.plot(history.history['accuracy'], label='train acc')
plt.plot(history.history['val_accuracy'], label='val acc')
plt.title('Accuracy of the model on training and validation sets')
plt.xlabel('Epochs')
plt.ylabel('Accuracy')
plt.legend()
plt.tight_layout()
plt.savefig('learning-curve.png')
plt.show()


# load the model that was saved as best model (most acc on validation data) and evaluate the model on test data
final_model = tf.keras.models.load_model('tf2_mnist_model.hdf5')

e_test = final_model.evaluate(
    test_images,
    to_categorical(test_labels)
)

print("Accuracy of the model on test set is" ,"{:.4f}".format(e_test[1]*100))



