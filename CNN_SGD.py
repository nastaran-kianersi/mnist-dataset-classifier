import tensorflow as tf
from keras.models import Sequential
from keras.layers import Dense, Conv2D, Flatten
import mnist
from keras.utils import to_categorical
import matplotlib.pyplot as plt
from keras import optimizers
from tensorflow.keras.callbacks import ModelCheckpoint
from sklearn.preprocessing import MinMaxScaler
from sklearn.model_selection import train_test_split

train_images = mnist.train_images()
train_labels = mnist.train_labels()

test_images = mnist.test_images()
test_labels = mnist.test_labels()

#normalization and flattening (28*28 to 784)
train_images = train_images.reshape((-1,784))
test_images = test_images.reshape((-1,784))

scaler = MinMaxScaler().fit(train_images)
train_images = scaler.transform(train_images)
test_images = scaler.transform(test_images)

#back to (28*28)
X_train = train_images.reshape(60000, 28,28,1)
X_test = test_images.reshape(10000, 28, 28, 1)

y_train_one_hot = to_categorical(train_labels)
y_test_one_hot = to_categorical(test_labels)

X_train, X_valid, y_train_one_hot, y_valid_one_hot = train_test_split(X_train, y_train_one_hot, test_size=0.2, random_state=18)


lrs = [0.001, 0.01, 0.1]

for lr in lrs:
  model = Sequential()
  # add model layers

  #change the activation function by uncommenting there lines:
  # =============================================================================
  #model.add(Conv2D(64, kernel_size=3, activation='softmax', input_shape=(28,28,1)))
  #model.add(Conv2D(32, kernel_size=3, activation='softmax'))
  # =============================================================================

  model.add(Conv2D(64, kernel_size=3, activation='relu', input_shape=(28,28,1)))
  model.add(Conv2D(32, kernel_size=3, activation='relu'))

  model.add(Flatten())
  model.add(Dense(10, activation='softmax'))

  sgd = optimizers.SGD(learning_rate=lr, decay=1e-6, momentum=0.9, nesterov=True)
  #Compile the model
  model.compile(optimizer=sgd, loss='categorical_crossentropy', metrics=['accuracy'])

  filepath = f'sgd-relu-{lr}-best-model.hdf5'
  checkpoint = ModelCheckpoint(filepath, monitor='val_accuracy', verbose=1, \
                              save_best_only=True, save_weights_only=False, \
                              mode='auto', save_frequency=1)
    
  hist = model.fit(X_train, y_train_one_hot, validation_data=(X_valid, y_valid_one_hot), \
                    epochs=5, batch_size=50, callbacks=[checkpoint]) 
    
  #Visualize the models accuracy
  plt.plot(hist.history['accuracy'], label='train acc')
  plt.plot(hist.history['val_accuracy'], label='test acc')
  plt.title('Model Accuracy')
  plt.ylabel('Accuracy')
  plt.xlabel('Epoch')
  plt.show()

  # load the model that was saved as best model (most acc on validation data) and evaluate the model on test data
  final_model = tf.keras.models.load_model(f'sgd-relu-{lr}-best-model.hdf5')

  e_test = final_model.evaluate(
      X_test,
      y_test_one_hot
  )

  print("Accuracy of the model on test data is" ,"{:.4f}".format(e_test[1]*100))